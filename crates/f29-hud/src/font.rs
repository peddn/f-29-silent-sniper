//! Eigener Vektor-Strichfont im Stil früher Kalligraphie-Displays.
//!
//! Jede Glyphe besteht aus Liniensegmenten auf einem 4 × 6-Raster
//! (x nach rechts, y nach oben). Da alles Linien sind, skaliert der Text
//! verlustfrei mit jeder Auflösung.

/// Segmente `(x0, y0, x1, y1)` im 4 × 6-Raster.
type Seg = (f32, f32, f32, f32);

const BOX: [Seg; 4] = [(0., 0., 4., 0.), (4., 0., 4., 6.), (4., 6., 0., 6.), (0., 6., 0., 0.)];

/// Liefert die Segmente einer Glyphe, `None` für unbekannte Zeichen.
pub fn glyph(c: char) -> Option<&'static [Seg]> {
    let g: &'static [Seg] = match c.to_ascii_uppercase() {
        ' ' => &[],
        '0' => &[BOX[0], BOX[1], BOX[2], BOX[3], (0., 0., 4., 6.)],
        '1' => &[(2., 0., 2., 6.), (2., 6., 1., 5.), (1., 0., 3., 0.)],
        '2' => &[(0., 6., 4., 6.), (4., 6., 4., 3.), (4., 3., 0., 3.), (0., 3., 0., 0.), (0., 0., 4., 0.)],
        '3' => &[(0., 6., 4., 6.), (4., 6., 4., 0.), (4., 0., 0., 0.), (1., 3., 4., 3.)],
        '4' => &[(0., 6., 0., 3.), (0., 3., 4., 3.), (4., 6., 4., 0.)],
        '5' | 'S' => {
            &[(4., 6., 0., 6.), (0., 6., 0., 3.), (0., 3., 4., 3.), (4., 3., 4., 0.), (4., 0., 0., 0.)]
        }
        '6' => &[(4., 6., 0., 6.), (0., 6., 0., 0.), (0., 0., 4., 0.), (4., 0., 4., 3.), (4., 3., 0., 3.)],
        '7' => &[(0., 6., 4., 6.), (4., 6., 1., 0.)],
        '8' => &[BOX[0], BOX[1], BOX[2], BOX[3], (0., 3., 4., 3.)],
        '9' => &[(4., 3., 0., 3.), (0., 3., 0., 6.), (0., 6., 4., 6.), (4., 6., 4., 0.), (4., 0., 0., 0.)],
        'A' => &[(0., 0., 0., 4.), (0., 4., 2., 6.), (2., 6., 4., 4.), (4., 4., 4., 0.), (0., 3., 4., 3.)],
        'B' => &[
            (0., 0., 0., 6.),
            (0., 6., 3., 6.),
            (3., 6., 4., 5.),
            (4., 5., 4., 4.),
            (4., 4., 3., 3.),
            (0., 3., 3., 3.),
            (3., 3., 4., 2.),
            (4., 2., 4., 1.),
            (4., 1., 3., 0.),
            (3., 0., 0., 0.),
        ],
        'C' => &[(4., 6., 0., 6.), (0., 6., 0., 0.), (0., 0., 4., 0.)],
        'D' => &[
            (0., 0., 0., 6.),
            (0., 6., 3., 6.),
            (3., 6., 4., 5.),
            (4., 5., 4., 1.),
            (4., 1., 3., 0.),
            (3., 0., 0., 0.),
        ],
        'E' => &[(4., 6., 0., 6.), (0., 6., 0., 0.), (0., 0., 4., 0.), (0., 3., 3., 3.)],
        'F' => &[(0., 0., 0., 6.), (0., 6., 4., 6.), (0., 3., 3., 3.)],
        'G' => &[(4., 6., 0., 6.), (0., 6., 0., 0.), (0., 0., 4., 0.), (4., 0., 4., 3.), (4., 3., 2., 3.)],
        'H' => &[(0., 0., 0., 6.), (4., 0., 4., 6.), (0., 3., 4., 3.)],
        'I' => &[(1., 6., 3., 6.), (2., 6., 2., 0.), (1., 0., 3., 0.)],
        'J' => &[(4., 6., 4., 0.), (4., 0., 0., 0.), (0., 0., 0., 2.)],
        'K' => &[(0., 0., 0., 6.), (0., 3., 4., 6.), (1., 3.75, 4., 0.)],
        'L' => &[(0., 6., 0., 0.), (0., 0., 4., 0.)],
        'M' => &[(0., 0., 0., 6.), (0., 6., 2., 3.), (2., 3., 4., 6.), (4., 6., 4., 0.)],
        'N' => &[(0., 0., 0., 6.), (0., 6., 4., 0.), (4., 0., 4., 6.)],
        'O' => &BOX,
        'P' => &[(0., 0., 0., 6.), (0., 6., 4., 6.), (4., 6., 4., 3.), (4., 3., 0., 3.)],
        'Q' => &[BOX[0], BOX[1], BOX[2], BOX[3], (2., 2., 4., 0.)],
        'R' => &[(0., 0., 0., 6.), (0., 6., 4., 6.), (4., 6., 4., 3.), (4., 3., 0., 3.), (1., 3., 4., 0.)],
        'T' => &[(0., 6., 4., 6.), (2., 6., 2., 0.)],
        'U' => &[(0., 6., 0., 0.), (0., 0., 4., 0.), (4., 0., 4., 6.)],
        'V' => &[(0., 6., 2., 0.), (2., 0., 4., 6.)],
        'W' => &[(0., 6., 1., 0.), (1., 0., 2., 3.), (2., 3., 3., 0.), (3., 0., 4., 6.)],
        'X' => &[(0., 0., 4., 6.), (0., 6., 4., 0.)],
        'Y' => &[(0., 6., 2., 3.), (4., 6., 2., 3.), (2., 3., 2., 0.)],
        'Z' => &[(0., 6., 4., 6.), (4., 6., 0., 0.), (0., 0., 4., 0.)],
        '-' => &[(1., 3., 3., 3.)],
        '+' => &[(2., 1., 2., 5.), (0., 3., 4., 3.)],
        '.' => &[(1.6, 0., 2.4, 0.), (2.4, 0., 2.4, 0.8), (2.4, 0.8, 1.6, 0.8), (1.6, 0.8, 1.6, 0.)],
        ':' => &[(2., 1., 2., 2.), (2., 4., 2., 5.)],
        '/' => &[(0., 0., 4., 6.)],
        '%' => &[(0., 0., 4., 6.), (0., 6., 0., 5.), (0., 5., 1., 5.), (4., 0., 4., 1.), (3., 1., 4., 1.)],
        '<' => &[(4., 6., 0., 3.), (0., 3., 4., 0.)],
        '>' => &[(0., 6., 4., 3.), (4., 3., 0., 0.)],
        '!' => &[(2., 6., 2., 2.), (2., 0.6, 2., 0.)],
        _ => return None,
    };
    Some(g)
}

/// Rasterhöhe einer Glyphe.
pub const GLYPH_H: f32 = 6.0;
/// Vorschub pro Zeichen in Rastereinheiten (4 Breite + 2 Abstand).
pub const ADVANCE: f32 = 6.0;

/// Breite eines Textes bei Zeichenhöhe `h`.
pub fn text_width(text: &str, h: f32) -> f32 {
    let n = text.chars().count() as f32;
    if n == 0.0 {
        return 0.0;
    }
    // letztes Zeichen ohne Abstand
    (n * ADVANCE - 2.0) * h / GLYPH_H
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn full_charset_present() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+.:/%<>! ".chars() {
            assert!(glyph(c).is_some(), "Glyphe fehlt: {c:?}");
        }
    }

    #[test]
    fn glyphs_stay_in_grid() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+.:/%<>!".chars() {
            for &(x0, y0, x1, y1) in glyph(c).unwrap() {
                for v in [x0, x1] {
                    assert!((0.0..=4.0).contains(&v), "{c}: x={v}");
                }
                for v in [y0, y1] {
                    assert!((0.0..=6.0).contains(&v), "{c}: y={v}");
                }
            }
        }
    }
}
